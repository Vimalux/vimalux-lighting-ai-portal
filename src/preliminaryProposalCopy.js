export function preliminaryProposalT(language, english) {
  if (language === "en" || language === "it") return english;
  const local = translations[language];
  if (!local || typeof english !== "string") return english;
  if (Object.hasOwn(local, english)) return local[english];
  for (const [pattern, render] of dynamic[language]) {
    const match = english.match(pattern);
    if (match) return render(...match);
  }
  return english; // Customer-entered names, product descriptions, values and codes.
}

