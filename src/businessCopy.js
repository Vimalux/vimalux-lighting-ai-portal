export function businessT(language, key, ...args) {
  const translation = translations[language]?.[key] ?? translations.en[key] ?? key;
  return typeof translation === "function" ? translation(...args) : translation;
}

export function missingBusinessTranslations() {
  return Object.fromEntries(Object.entries(translations).map(([locale, dict]) =>
    [locale, Object.keys(translations.en).filter((key) => !dict[key])]));
}
