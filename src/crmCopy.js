export function crmT(language, key) {
  return crmCopy[language]?.[key] || crmCopy.en[key] || key;
}

export function crmTranslationCoverage() {
  const expected = Object.keys(crmCopy.en);
  return Object.fromEntries(Object.entries(crmCopy).map(([language, messages]) => [
    language,
    expected.filter((key) => !messages[key]),
  ]));
}
